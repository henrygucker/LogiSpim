package org.henrygucker.logispim.fileprocessor.actionlisteners;

import org.henrygucker.logispim.fileprocessor.backend.*;
import org.henrygucker.logispim.fileprocessor.backend.exceptions.CompilationException;
import org.henrygucker.logispim.fileprocessor.backend.fileutils.FileUtil;
import org.henrygucker.logispim.fileprocessor.backend.elf.ElfFile;
import org.henrygucker.logispim.fileprocessor.backend.elf.ElfFormatException;
import org.henrygucker.logispim.fileprocessor.App;
import org.henrygucker.logispim.fileprocessor.backend.fileutils.ResourceFileUtil;

import javax.swing.*;
import java.awt.event.ActionEvent;
import java.awt.event.ActionListener;
import java.io.*;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.concurrent.TimeUnit;

public class CompileActionListener implements ActionListener {

    private final App app;
    private final HexFileCompiler hexFileCompiler;

    private static Thread worker = null;

    public CompileActionListener(App app) {
        this.app = app;
        this.hexFileCompiler = new HexFileCompiler(app);
    }

    @Override
    public void actionPerformed(ActionEvent e) {
        if (this.worker != null && this.worker.isAlive())
            // Ignores compile button press if the worker thread has not completed
            return;

        // Use of worker thread to allow for GUI to remain responsive
        Thread worker = new Thread(this::performAction);
        worker.start();
    }

    private synchronized void performAction() {
        // Getting config values for compilation
        Path outputDir = WorkspaceFileHandler.getOutputDir();
        Path sourcePath = (Path) AppConfig.LAST_CHOSEN_SOURCE_FILE_PATH.getValue();
        boolean isKernelText = (boolean) AppConfig.IS_KERNEL_TEXT.getValue();

        // Checking validity of read values

        // Invalid if was unable to get path (null returned) or if path is not directed at a directory
        if (!outputDir.toFile().exists() || !outputDir.toFile().isDirectory()) {
            app.errorMessage("Compilation Error", "Invalid output directory selected.");
            return;
        }

        // Invalid if source file does not exist
        if (!sourcePath.toFile().exists()) {
            app.errorMessage("Compilation Error", "Invalid source path selected. No file at \"" + sourcePath.toString() + "\" exists.");
            return;
        }

        // Invalid if source "file" is a directory
        if (sourcePath.toFile().isDirectory()) {
            app.errorMessage("Compilation Error", "Invalid source path selected. \"" + sourcePath.toString() + "\" is a directly, not a file.");
            return;
        }

        // Get ELF file & path
        Path elfPath = generateElfFile(sourcePath, outputDir, isKernelText);

        // Issue occurred in generateElfFile(), and action exits. Notification was generated by generateElfFile()
        if (elfPath == null)
            return;

        // Parse ELF file
        ElfFile elfFile = null;
        try {
            elfFile = new ElfFile(elfPath);
        } catch (IOException e) {
           app.errorMessage("Compilation Error", "An error occurred while reading compiled ELF file. Try again.");
           return;
        } catch (ElfFormatException e) {
            app.errorMessage("Compilation Error", e.getMessage());
            return;
        }

        String sourceName = sourcePath.getFileName().toString().split("\\.")[0];

        // elfPath is located in /outputDir/sourceName/bin/sourceName.elf
        // elfPath.getParent().getParent() is then /outputDir/sourceName
        Path targetOutputDir = elfPath.getParent().getParent();
        Path textOutputFile = targetOutputDir.resolve("text.hex");
        Path dataOutputFile = targetOutputDir.resolve("data.hex");
        Path kernelTextOutputFile = targetOutputDir.resolve("text-kernel.hex");
        Path disassemblyOutputFile = targetOutputDir.resolve("disassembly-asm.lss");

        Path[] outputFilePaths = new Path[]{
                textOutputFile,
                dataOutputFile,
                kernelTextOutputFile,
                disassemblyOutputFile
        };

        // Purges old output files to not confuse users if compilation fails or if program with same name is compiled as
        // non-kernel text, and then is compiled as kernel text.
        for (int i = 0; i < outputFilePaths.length; i++) {
            try {
                FileUtil.deleteRecursive(outputFilePaths[i]);
            } catch (IOException e) {
                app.errorMessage(
                        "Compilation Error",
                        "An IO issue occurred while deleting contents occupying output location \"" +
                        outputFilePaths[i].toAbsolutePath().toString() + "\". Try again."
                );
                return;
            } catch (SecurityException e) {
                app.errorMessage(
                        "Compilation Error",
                        "This process lacks permission to delete contents occupying output location \"" +
                                outputFilePaths[i].toAbsolutePath().toString() + "\"."
                );
            }
        }

        // Write appropriate files
        if (isKernelText) {
            hexFileCompiler.writeKernelTextBinaryFiles(elfFile, kernelTextOutputFile);
        } else {
            hexFileCompiler.writeNonKernelTextBinaryFiles(elfFile, textOutputFile, dataOutputFile);
        }


        // Get objdump output
        String objdumpOutput = getObjdumpFilteredOutput(elfPath);

        // Write output to text area
        app.updateTextArea(objdumpOutput);

        // Writing .lss disassembly file for viewing in Logisim
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(disassemblyOutputFile.toFile()))) {
            writer.write(objdumpOutput);

        } catch (IOException e) {
            app.updateTextArea("An error occurred while writing disassembly content to file.");
            return;
        }

        // Write success notification
        JOptionPane.showMessageDialog(
                app,
                "Output files can be found in \"" + targetOutputDir.toString() + "\".",
                "Compilation Complete",
                JOptionPane.PLAIN_MESSAGE
        );
    }

    /**
     * Generates ELF file from source MIPS assembly file following the given parameters.
     * @param sourcePath {@link Path} to source MIPS assembly file.
     * @param outputDir {@link Path} to app output directory.
     * @param isKernelText {@code true} if compiling kernel instructions, otherwise {@code false}.
     * @return {@link Path} to generated ELF file.
     */
    private Path generateElfFile(Path sourcePath, Path outputDir, boolean isKernelText) {
        String sourceName = sourcePath.getFileName().toString().split("\\.")[0];
        Path targetOutputDir = outputDir.resolve(sourceName);
        Path targetOutputBinDir = targetOutputDir.resolve("bin");

        Path linkerScriptPath = targetOutputBinDir.resolve("linkerscript.ld");
        try {
            linkerScriptPath = ResourceFileUtil.writeLinkerScript(isKernelText, linkerScriptPath);
        } catch (IOException e) {
            app.errorMessage("Compilation Error", "An error occurred while generating linker script.");

            return null;
        }

        Path preProcessedSourcePath = targetOutputBinDir.resolve(sourceName + "_processed.s");
        Path elfPath = null;
        try {
            elfPath = MIPSCrossCompiler.compile(sourcePath, linkerScriptPath, outputDir, isKernelText);
        } catch (CompilationException e) {
            app.updateTextAreaWithFileContent(preProcessedSourcePath);
            app.errorMessage(e.getTitle(), e.getIsolatedMessage());
        } catch (IOException | InterruptedException e) {
            app.errorMessage("Compilation Error", "An error occurred during the back-end compilation process. Try again.");
        }

        return elfPath;
    }

    private String getObjdumpFilteredOutput(Path elfPath) {
        // Build CLI args
        ArrayList<String> objdumpArgs = new ArrayList<>();
        for (String arg : OSDependentData.getForCurrentOS().getObjdumpCommand())
            objdumpArgs.add(arg);

        objdumpArgs.add("-D");

        objdumpArgs.add(OSDependentData.pathToOSString(elfPath));

        // Build objdump process
        ProcessBuilder pb = new ProcessBuilder(objdumpArgs);
        Process objdump = null;
        try {
            // Start objdump process
            objdump = pb.start();
        } catch (IOException e) {
            return "An IO error occurred when fetching instructions.\nTry again.";
        }

        // Only stores lines in data and text sections
        boolean shouldStoreLines = false;
        StringBuilder objdumpOutputBuilder = new StringBuilder();
        try (BufferedReader bufferedReader = new BufferedReader(new InputStreamReader(objdump.getInputStream()))) {
            String line;
            while ((line = bufferedReader.readLine()) != null) {

                // Start storing lines at start of text or data sections, stop at start of any other sections
                if (line.equals("Disassembly of section .text:"))
                    shouldStoreLines = true;
                else if (line.equals("Disassembly of section .data:"))
                    shouldStoreLines = true;
                else if (line.startsWith("Disassembly of section "))
                    shouldStoreLines = false;

                // Store line (if in text or data sections)
                if (shouldStoreLines) {
                    objdumpOutputBuilder.append(line);
                    objdumpOutputBuilder.append('\n');
                }
            }
        } catch (IOException e) {
            return "Error when fetching instructions.\n" +
                    "An issue occurred with IO.";
        }

        // Set timeout on objdump execution
        try {
            objdump.waitFor(15, TimeUnit.SECONDS);
        } catch (InterruptedException e) {
            return "Error when fetching instructions.\n" +
                    "Worker thread interrupted.";
        }

        // Check if objdump exceeded timeout
        if (objdump.isAlive()) {
            objdump.destroy();

            return "Error when fetching instructions.\n" +
                    "Runtime limit exceeded.";
        }

        return objdumpOutputBuilder.toString();
    }

}
